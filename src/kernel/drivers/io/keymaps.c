uint8_t get_key_code_ascii_pressed(uint8_t key_code, int modifier_flags[])
{
    for (int i = 0; i < 6; i++) 
    {
        for (int j = 0; j < 17; j++) 
        {
            if (key_code_pressed[i][j] == key_code) 
            {
                if (modifier_flags[0] == 1 || modifier_flags[1] == 1)
                {
                    return key_vals_caps[i][j];
                } else if (modifier_flags[2] == 1)
                {
                    return key_vals_alt[i][j];
                } else
                {
                    return key_vals[i][j];
                }
                
                 // Return the ASCII code directly
            }
        }
    }
    return 0;
}

